// LeetCode 27: Remove Element
// Approach: Two-pointer overwrite in-place
// Time Complexity: O(n), Space Complexity: O(1)

#include <vector>
using namespace std;

class Solution {
public:
    int removeElement(vector<int>& nums, int val) {
        int k = 0;
        for (int i = 0; i < nums.size(); i++) {
            if (nums[i] != val) {
                nums[k++] = nums[i];
            }
        }
        return k;
    }
};
